export interface ThemeTokens {
  /** Hintergrund der Box (Farbe oder Verlauf) */
  boxBg: string;
  boxBorder: string;
  /** Optionale Akzentkante oben (wie „glühende“ Oberkante) */
  boxBorderTop?: string;
  boxShadow: string;
  text: string;
  muted: string;
  heading: string;
  headline: string;
  headlineShadow: string;
  innerBg: string;
  innerBorder: string;
  pillBg: string;
  pillText: string;
  eyebrowBg: string;
  eyebrowBorder: string;
  eyebrowText: string;
  buttonBg: string;
  buttonText: string;
  buttonShadow: string;
  chipBg: string;
  chipBorder: string;
  chipText: string;
  /* Optionale Struktur-Merkmale – machen Themes mehr als nur Farbvarianten */
  titleShadow?: string;
  titleTransform?: 'uppercase' | 'none';
  titleLetterSpacing?: string;
  titleStyle?: 'italic' | 'normal';
  /** Leichte Schrägstellung der Boxen in Grad (abwechselnd links/rechts) */
  tilt?: number;
  pillRadius?: string;
  eyebrowRadius?: string;
  /** Rundung innerer Zeilen/Karten in px */
  innerRadius?: number;
}

